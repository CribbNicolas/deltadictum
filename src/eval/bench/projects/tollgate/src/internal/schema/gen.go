package schema

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

type spec struct {
	Types []struct {
		Name   string `json:"name"`
		Fields []struct {
			Name string `json:"name"`
			Type string `json:"type"`
		} `json:"fields"`
	} `json:"types"`
}

var goTypes = map[string]string{"string": "string", "int": "int64", "bool": "bool"}

// Generate returns the Go source of types_gen.go for an events.json document.
func Generate(data []byte) ([]byte, error) {
	var s spec
	if err := json.Unmarshal(data, &s); err != nil {
		return nil, fmt.Errorf("schema: %w", err)
	}
	sort.Slice(s.Types, func(i, j int) bool { return s.Types[i].Name < s.Types[j].Name })
	var b bytes.Buffer
	b.WriteString("// Code generated by schemagen. DO NOT EDIT.\n\npackage schema\n\n")
	b.WriteString("// Known maps each accepted event type to its payload fields.\nvar Known = map[string][]Field{\n")
	for _, t := range s.Types {
		fmt.Fprintf(&b, "%q: {", t.Name)
		for i, f := range t.Fields {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "{Name: %q, Type: %q}", f.Name, f.Type)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	for _, t := range s.Types {
		fmt.Fprintf(&b, "\n// %s is the payload of %s events.\ntype %s struct {\n", ident(t.Name), t.Name, ident(t.Name))
		for _, f := range t.Fields {
			gt, ok := goTypes[f.Type]
			if !ok {
				return nil, fmt.Errorf("schema: %s.%s: unknown type %q", t.Name, f.Name, f.Type)
			}
			fmt.Fprintf(&b, "%s %s `json:%q`\n", ident(f.Name), gt, f.Name)
		}
		b.WriteString("}\n")
	}
	return format.Source(b.Bytes())
}

func ident(name string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(name, func(r rune) bool { return r == '.' || r == '_' }) {
		if part == "id" {
			b.WriteString("ID")
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}
