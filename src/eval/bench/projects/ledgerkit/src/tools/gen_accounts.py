"""Writes ledgerkit/accounts_gen.py from chart/accounts.csv.

    python tools/gen_accounts.py
"""

import csv
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = "# Generated by tools/gen_accounts.py from chart/accounts.csv. Do not edit.\n"


def generate(chart: str) -> str:
    """The Python source of accounts_gen.py for the text of accounts.csv."""
    reader = csv.reader(io.StringIO(chart), delimiter=";")
    next(reader)
    accounts = sorted((int(number), name.strip()) for number, name in (row for row in reader if row))
    body = "".join(f"    {number}: {name!r},\n" for number, name in accounts)
    return f"{HEADER}\nACCOUNTS = {{\n{body}}}\n"


def main() -> int:
    with open(os.path.join(ROOT, "chart", "accounts.csv"), encoding="utf-8") as f:
        source = generate(f.read())
    with open(os.path.join(ROOT, "ledgerkit", "accounts_gen.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
    return 0


if __name__ == "__main__":
    sys.exit(main())
